// Artwork pipeline: catalog.json -> WebP files, generated catalog.ts, app icons, licenses check.
// Run from frontend/ via `npm run artwork`. Idempotent.
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import fs from 'node:fs'

const here = path.dirname(fileURLToPath(import.meta.url))
const artworkDir = path.resolve(here, '..')
const frontend = path.resolve(artworkDir, '..', 'frontend')
const require = createRequire(path.join(frontend, 'package.json'))
const sharp = require('sharp')

const pkgDir = path.join(frontend, 'node_modules', '@lobehub', 'fluent-emoji-3d')
const assetsDir = path.join(pkgDir, 'assets')
const outDir = path.join(frontend, 'public', 'artwork')
const iconsDir = path.join(frontend, 'public', 'icons')
const catalogPath = path.join(artworkDir, 'catalog.json')
const tsPath = path.join(frontend, 'src', 'artwork', 'catalog.ts')

fs.mkdirSync(outDir, { recursive: true })
fs.mkdirSync(iconsDir, { recursive: true })
fs.mkdirSync(path.dirname(tsPath), { recursive: true })

const hex = (s) => [...s].map((c) => c.codePointAt(0).toString(16).padStart(4, '0'))
function resolveSource(emoji) {
  const cps = hex(emoji)
  const noVs = cps.filter((c) => c !== 'fe0f')
  const withVs = []
  for (const c of noVs) {
    withVs.push(c)
  }
  const candidates = [cps.join('-'), noVs.join('-'), [noVs[0], 'fe0f', ...noVs.slice(1)].join('-')]
  // Also try inserting fe0f after each codepoint (ZWJ sequences)
  candidates.push(noVs.flatMap((c) => (c === '200d' ? [c] : [c, 'fe0f'])).join('-').replace(/-fe0f$/, ''))
  candidates.push(noVs.flatMap((c) => (c === '200d' ? [c] : [c, 'fe0f'])).join('-'))
  for (const name of new Set(candidates)) {
    if (fs.existsSync(path.join(assetsDir, `${name}.webp`))) return name
  }
  return null
}

const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'))
let converted = 0
let totalBytes = 0
const missing = []
const keep = new Set()

for (const entry of catalog) {
  const name = resolveSource(entry.emoji)
  if (!name) {
    entry.source = null
    missing.push(entry.key)
    continue
  }
  entry.source = `node_modules/@lobehub/fluent-emoji-3d/assets/${name}.webp`
  const out = path.join(outDir, `${entry.key}.webp`)
  await sharp(path.join(assetsDir, `${name}.webp`))
    .resize(256, 256, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .webp({ quality: 82 })
    .toFile(out)
  totalBytes += fs.statSync(out).size
  keep.add(`${entry.key}.webp`)
  converted++
}
for (const f of fs.readdirSync(outDir)) {
  if (f.endsWith('.webp') && !keep.has(f)) fs.unlinkSync(path.join(outDir, f))
}
fs.writeFileSync(catalogPath, JSON.stringify(catalog, null, 2) + '\n')

const entries = catalog.map((e) => ({
  key: e.key,
  name: e.name,
  emoji: e.emoji,
  tags: e.tags ?? [],
  uses: e.uses,
  category: e.category ?? null,
  file: e.source ? `/artwork/${e.key}.webp` : null,
}))
const ts = `// GENERATED by artwork/scripts/build-artwork.mjs - do not edit.
export type ArtworkUse = 'sticker' | 'task' | 'routine' | 'avatar'

export interface ArtworkEntry {
  key: string
  name: string
  emoji: string
  tags: string[]
  uses: ArtworkUse[]
  category: string | null
  file: string | null
}

export const ARTWORK_LIST: readonly ArtworkEntry[] = ${JSON.stringify(entries, null, 2)}

export const ARTWORK: Readonly<Record<string, ArtworkEntry>> = Object.fromEntries(
  ARTWORK_LIST.map((e) => [e.key, e]),
)

export function artworkForUse(use: ArtworkUse): ArtworkEntry[] {
  return ARTWORK_LIST.filter((e) => e.uses.includes(use))
}

export function getArtwork(key: string): ArtworkEntry | undefined {
  return Object.prototype.hasOwnProperty.call(ARTWORK, key) ? ARTWORK[key] : undefined
}
`
fs.writeFileSync(tsPath, ts)

// App icons
const svg = fs.readFileSync(path.join(artworkDir, 'app-icon.svg'))
for (const [name, size] of [['icon-192.png', 192], ['icon-512.png', 512]]) {
  await sharp(svg, { density: 384 }).resize(size, size).png().toFile(path.join(iconsDir, name))
}
// Maskable: full-bleed background, artwork inside 80% safe zone
const inner = Math.round(512 * 0.7)
const innerBuf = await sharp(svg, { density: 384 }).resize(inner, inner).png().toBuffer()
await sharp({ create: { width: 512, height: 512, channels: 4, background: '#FFB703' } })
  .composite([{ input: innerBuf, gravity: 'center' }])
  .png()
  .toFile(path.join(iconsDir, 'icon-maskable-512.png'))
// Apple touch icon: opaque 180x180
await sharp(svg, { density: 384 })
  .resize(180, 180)
  .flatten({ background: '#FFB703' })
  .png()
  .toFile(path.join(iconsDir, 'apple-touch-icon.png'))

console.log(`artwork: converted=${converted} missing=${missing.length} total=${catalog.length} bytes=${totalBytes} (${(totalBytes / 1048576).toFixed(2)} MiB)`)
if (missing.length) console.log(`missing images: ${missing.join(', ')}`)
console.log('icons: icon-192, icon-512, icon-maskable-512, apple-touch-icon written')
