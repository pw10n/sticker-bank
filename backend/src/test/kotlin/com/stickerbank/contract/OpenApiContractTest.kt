package com.stickerbank.contract

import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Assertions.fail
import org.junit.jupiter.api.Test
import org.springframework.beans.factory.annotation.Autowired
import org.springframework.boot.test.context.SpringBootTest
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc
import org.springframework.test.web.servlet.MockMvc
import org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get
import org.springframework.test.web.servlet.result.MockMvcResultMatchers.status
import tools.jackson.databind.JsonNode
import tools.jackson.databind.json.JsonMapper
import java.nio.charset.StandardCharsets
import java.nio.file.Files
import java.nio.file.Path

/**
 * TDD 8.1: the OpenAPI spec generated by springdoc must equal the committed frontend contract.
 * Needs no database: Flyway and Spring Data JDBC repositories are switched off and no query runs while generating the spec.
 * Regenerate with: UPDATE_OPENAPI=true ./gradlew test --tests '*OpenApiContractTest'
 */
@SpringBootTest(
    webEnvironment = SpringBootTest.WebEnvironment.MOCK,
    properties = [
        "spring.flyway.enabled=false",
        "spring.datasource.url=jdbc:mysql://127.0.0.1:1/none",
        "spring.datasource.username=contract",
        "spring.datasource.password=contract",
        "spring.datasource.hikari.initialization-fail-timeout=-1",
        "spring.autoconfigure.exclude=org.springframework.boot.data.jdbc.autoconfigure.DataJdbcRepositoriesAutoConfiguration",
        // sample controllers declared by other test classes share the component scan; they are not part of the API
        "springdoc.paths-to-exclude=/api/test/**,/other/**",
        "management.endpoint.health.group.readiness.include=readinessState",
    ],
)
@AutoConfigureMockMvc
class OpenApiContractTest {
    @Autowired
    lateinit var mvc: MockMvc

    private val mapper = JsonMapper.builder().build()

    @Test
    fun `committed openapi json matches the generated spec`() {
        val body =
            mvc.perform(get("/api/openapi.json")).andExpect(status().isOk).andReturn()
                .response.getContentAsString(StandardCharsets.UTF_8)
        val generated = mapper.readTree(mapper.writeValueAsString(sorted(mapper.readTree(body))))
        val file = contractFile()

        if (updateRequested()) {
            Files.writeString(file, mapper.writerWithDefaultPrettyPrinter().writeValueAsString(sorted(generated)) + "\n")
            return
        }

        assertTrue(Files.exists(file)) { "Missing $file. Run: UPDATE_OPENAPI=true ./gradlew test --tests '*OpenApiContractTest'" }
        val committed = mapper.readTree(Files.readString(file))
        if (committed != generated) {
            val diffs = diff("", committed, generated)
            fail<Unit>(
                "frontend/src/api/openapi.json is out of date (${diffs.size} differences). " +
                    "Run: UPDATE_OPENAPI=true ./gradlew test --tests '*OpenApiContractTest'\n" +
                    diffs.take(40).joinToString("\n") +
                    if (diffs.size > 40) "\n... and ${diffs.size - 40} more" else "",
            )
        }
    }

    private fun updateRequested(): Boolean =
        (System.getProperty("UPDATE_OPENAPI") ?: System.getenv("UPDATE_OPENAPI")).equals("true", ignoreCase = true)

    /** Gradle runs tests with cwd = backend/; from the repo root or an IDE the frontend dir sits one level down. */
    private fun contractFile(): Path {
        val cwd = Path.of("").toAbsolutePath()
        val candidates = listOf(cwd.resolve("../frontend"), cwd.resolve("frontend"))
        val frontend = candidates.firstOrNull { Files.isDirectory(it) } ?: fail<Path>("frontend directory not found from $cwd")
        return frontend.resolve("src/api/openapi.json").normalize()
    }

    private fun sorted(node: JsonNode): JsonNode = when {
        node.isObject ->
            mapper.createObjectNode().also { out ->
                node.properties().sortedBy { it.key }.forEach { out.set(it.key, sorted(it.value)) }
            }
        node.isArray -> mapper.createArrayNode().also { out -> node.forEach { out.add(sorted(it)) } }
        else -> node
    }

    private fun diff(path: String, committed: JsonNode?, generated: JsonNode?): List<String> {
        if (committed == generated) return emptyList()
        if (committed == null) return listOf("+ $path (only in generated): ${generated.toString().take(120)}")
        if (generated == null) return listOf("- $path (only in committed): ${committed.toString().take(120)}")
        if (committed.isObject && generated.isObject) {
            val keys = (committed.properties().map { it.key } + generated.properties().map { it.key }).toSortedSet()
            return keys.flatMap { diff("$path/$it", committed.get(it), generated.get(it)) }
        }
        if (committed.isArray && generated.isArray && committed.size() == generated.size()) {
            return (0 until committed.size()).flatMap { diff("$path/$it", committed.get(it), generated.get(it)) }
        }
        return listOf("~ $path: committed=${committed.toString().take(120)} generated=${generated.toString().take(120)}")
    }
}
